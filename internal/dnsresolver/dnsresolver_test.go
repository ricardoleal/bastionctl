// commandRunner records every command. When execFS is set, the install/rm
// commands are simulated against the real filesystem (files copied with
// 0644 perms), so darwin-based assertions work on any platform without
// invoking actual `sudo`/`install`/`ip`. Unmatched commands fall back to the
// scripted results map, then to a no-op.
type commandRunner struct {
	commands [][]string
	execFS   bool
	results  map[string]result // key: full command line
}

type result struct {
	out []byte
	err error
}

func (r *commandRunner) Run(name string, args ...string) ([]byte, error) {
	all := append([]string{name}, args...)
	r.commands = append(r.commands, all)
	key := strings.Join(all, " ")
	if res, ok := r.results[key]; ok {
		return res.out, res.err
	}
	if r.execFS {
		return r.execSimulated(name, args)
	}
	return nil, nil
}

func (r *commandRunner) execSimulated(name string, args []string) ([]byte, error) {
	switch name {
	case "install":
		if len(args) > 0 && args[0] == "-d" {
			dir := args[len(args)-1]
			if err := os.MkdirAll(dir, 0o755); err != nil {
				return nil, err
			}
			return nil, nil
		}
		if len(args) < 2 {
			return nil, errors.New("simulated install: missing arguments")
		}
		src, dest := args[len(args)-2], args[len(args)-1]
		data, err := os.ReadFile(src)
		if err != nil {
			return nil, err
		}
		if err := os.WriteFile(dest, data, 0o644); err != nil {
			return nil, err
		}
		return nil, nil
	case "rm":
		if len(args) < 1 {
			return nil, errors.New("simulated rm: missing arguments")
		}
		target := args[len(args)-1]
		if err := os.Remove(target); err != nil && !os.IsNotExist(err) {
			return nil, err
		}
		return nil, nil
	case "sudo":
		if len(args) == 0 {
			return nil, errors.New("simulated sudo: missing arguments")
		}
		return r.execSimulated(args[0], args[1:])
	default:
		// ip/resolvectl/telemetry commands are only exercised through the
		// scripted results map in these tests.
		return nil, nil
	}
}

func splitTestOptions(t *testing.T, goos string, execFS bool) (*Options, *commandRunner, string) {
	t.Helper()
	tempRoot := t.TempDir()
	etcResolver := filepath.Join(tempRoot, "etc", "resolver")
	if err := os.MkdirAll(etcResolver, 0o755); err != nil {
		t.Fatal(err)
	}
	runner := &commandRunner{execFS: execFS, results: map[string]result{}}
	o := &Options{
		GoOS:           goos,
		EtcResolverDir: etcResolver,
		Run:            runner.Run,
		LookPath:       func(name string) (string, error) { return "/usr/bin/" + name, nil },
		TerminalIn:     true, // bypass the sudo -n fail-fast in tests
		EUID:           0,    // no sudo prefix by default
	}
	return o, runner, etcResolver
}

func testConfig(connection string) *config.Config {
	return &config.Config{
		Name: connection,
		DNS: &config.DNSConfig{
			Mode:     config.DNSModeSplit,
			Resolver: []string{"10.0.0.2"},
			Domains:  []string{"corp.internal", "svc.cluster.local"},
		},
	}
}

func assertFile(t *testing.T, path, wantContent string) {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("reading %s: %v", path, err)
	}
	if string(data) != wantContent {
		t.Fatalf("content of %s = %q, want %q", path, data, wantContent)
	}
}

func flatten(commands [][]string) []string {
	out := make([]string, len(commands))
	for i, cmd := range commands {
		out[i] = strings.Join(cmd, " ")
	}
	return out
}

const resolverContent = generatedHeaderPrefix + "corp\nnameserver 10.0.0.2\nport 53\n"

func TestDarwinInstallWritesTaggedResolverFiles(t *testing.T) {
	o, runner, etc := splitTestOptions(t, "darwin", true)
	statePath := filepath.Join(t.TempDir(), "corp.dns-state.yaml")

	state, err := o.Install(testConfig("corp"), statePath)
	if err != nil {
		t.Fatal(err)
	}

	want := resolverContent
	assertFile(t, filepath.Join(etc, "corp.internal"), want)
	assertFile(t, filepath.Join(etc, "svc.cluster.local"), want)
	if len(state.Files) != 2 {
		t.Fatalf("state files = %#v", state.Files)
	}
	for _, record := range state.Files {
		if record.SHA256 == "" {
			t.Fatal("state record missing content hash")
		}
	}
	for _, cmd := range runner.commands {
		if cmd[0] == "sudo" {
			t.Fatalf("unexpected sudo prefix while root: %v", cmd)
		}
	}
}

func TestDarwinInstallRefusesForeignAndOtherConnectionFiles(t *testing.T) {
	cases := []struct {
		name    string
		content string
		wantErr string
	}{
		{
			name:    "other connection",
			content: generatedHeaderPrefix + "other\nnameserver 10.0.0.2\nport 53\n",
			wantErr: `managed by connection "other"`,
		},
		{
			name:    "foreign file",
			content: "nameserver 8.8.8.8\n",
			wantErr: "was not generated by bastionctl",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			o, _, etc := splitTestOptions(t, "darwin", false)
			if err := os.WriteFile(filepath.Join(etc, "corp.internal"), []byte(tc.content), 0o644); err != nil {
				t.Fatal(err)
			}
			_, err := o.Install(testConfig("corp"), filepath.Join(t.TempDir(), "state.yaml"))
			if err == nil || !strings.Contains(err.Error(), tc.wantErr) {
				t.Fatalf("error = %v, want substring %q", err, tc.wantErr)
			}
		})
	}
}

func TestDarwinReinstallSameConnectionAndReconcilesStaleDomains(t *testing.T) {
	o, runner, etc := splitTestOptions(t, "darwin", true)
	statePath := filepath.Join(t.TempDir(), "corp.dns-state.yaml")

	if _, err := o.Install(testConfig("corp"), statePath); err != nil {
		t.Fatal(err)
	}
	cfg := testConfig("corp")
	cfg.DNS.Domains = []string{"corp.internal"} // svc.cluster.local must go away
	state, err := o.Install(cfg, statePath)
	if err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(etc, "svc.cluster.local")); !os.IsNotExist(err) {
		t.Fatalf("stale resolver file still present: %v", err)
	}
	assertFile(t, filepath.Join(etc, "corp.internal"), resolverContent)
	if len(state.Files) != 1 {
		t.Fatalf("state files = %#v", state.Files)
	}
	foundRemoval := false
	for _, cmd := range flatten(runner.commands) {
		if strings.Contains(cmd, "rm -f "+filepath.Join(etc, "svc.cluster.local")) {
			foundRemoval = true
		}
	}
	if !foundRemoval {
		t.Fatalf("stale file removal not attempted; commands = %#v", runner.commands)
	}
}

func TestDarwinRemoveChecksOwnershipAndHash(t *testing.T) {
	o, _, etc := splitTestOptions(t, "darwin", true)
	oursPath := filepath.Join(etc, "corp.internal")
	if err := os.WriteFile(oursPath, []byte(resolverContent), 0o644); err != nil {
		t.Fatal(err)
	}
	foreignContent := generatedHeaderPrefix + "other\nnameserver 10.0.0.2\n"
	foreignPath := filepath.Join(etc, "other.internal")
	if err := os.WriteFile(foreignPath, []byte(foreignContent), 0o644); err != nil {
		t.Fatal(err)
	}
	unknownContent := "nameserver 192.168.1.1\n"
	unknownPath := filepath.Join(etc, "home.internal")
	if err := os.WriteFile(unknownPath, []byte(unknownContent), 0o644); err != nil {
		t.Fatal(err)
	}

	state := &State{
		Platform:   "darwin",
		Connection: "corp",
		Domains:    []string{"corp.internal", "other.internal", "home.internal"},
		Resolver:   []string{"10.0.0.2"},
		Files: []FileRecord{
			{Path: oursPath, SHA256: sha256Hex([]byte(resolverContent))},
			{Path: foreignPath, SHA256: sha256Hex([]byte(foreignContent))},
			{Path: unknownPath, SHA256: sha256Hex([]byte(unknownContent))},
			{Path: filepath.Join(etc, "missing.internal"), SHA256: "abc"},
		},
	}
	warnings, err := o.Remove(state)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(oursPath); !os.IsNotExist(err) {
		t.Fatalf("owned file not removed: %v", err)
	}
	for _, path := range []string{foreignPath, unknownPath} {
		if _, err := os.Stat(path); err != nil {
			t.Fatalf("foreign file %s was touched: %v", path, err)
		}
	}
	if len(warnings) != 2 {
		t.Fatalf("warnings = %#v", warnings)
	}
}

