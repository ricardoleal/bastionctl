// Package dnsresolver installs and removes the OS-level per-domain resolver
// configuration that bastionctl's split-DNS mode depends on.
//
// sshuttle cannot filter DNS by domain: --ns-hosts captures only queries sent
// to specific resolver IPs, and something still has to route only the chosen
// domain suffixes to one of those IPs. That routing lives in the OS resolver:
//
//   - macOS: /etc/resolver/<domain> files with a nameserver directive.
//   - Linux: a bastionctl dummy link registered with systemd-resolved via
//     `resolvectl dns/domain` (routing domains prefixed with ~).
//
// Installation is record-protected: every artifact is tagged with a
// "Generated by bastionctl for connection <name>" header and a content hash
// so teardown only removes what this connection owns, warns about files
// edited after install, and never touches foreign files or links.
package dnsresolver

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"runtime"
	"strings"
	"time"

	"golang.org/x/term"

	"bastionctl/internal/config"
)

// generatedHeaderPrefix tags every file bastionctl writes so teardown can
// distinguish its own artifacts from foreign resolver files.
const generatedHeaderPrefix = "# Generated by bastionctl for connection "

// Options abstracts the environment so both the darwin and linux code paths
// can be exercised from tests on any platform (with a fake runner, a fake
// PATH lookup, and a scratch directory standing in for /etc/resolver).
type Options struct {
	GoOS           string
	EtcResolverDir string // darwin: base directory for resolver files.
	Run            func(name string, args ...string) ([]byte, error)
	LookPath       func(name string) (string, error)
	TerminalIn     bool
	EUID           int
}

// DefaultOptions builds the real execution environment for the running OS.
func DefaultOptions() *Options {
	o := &Options{
		GoOS:           runtime.GOOS,
		EtcResolverDir: "/etc/resolver",
		Run: func(name string, args ...string) ([]byte, error) {
			return exec.Command(name, args...).CombinedOutput()
		},
		LookPath:   exec.LookPath,
		TerminalIn: term.IsTerminal(int(os.Stdin.Fd())),
		EUID:       os.Geteuid(),
	}
	return o
}

// Install brings the OS resolver config in line with cfg.DNS (which must be
// a fully normalized split configuration) and records what was touched in
// statePath for later teardown.
func Install(cfg *config.Config, statePath string) (*State, error) {
	return DefaultOptions().Install(cfg, statePath)
}

// Install is the options-parametrized variant used by tests.
func (o *Options) Install(cfg *config.Config, statePath string) (*State, error) {
	d := cfg.DNS
	if d == nil || d.EffectiveMode() != config.DNSModeSplit {
		return nil, errors.New("installing split-DNS resolver config requires a connection in split mode")
	}
	if len(d.Domains) == 0 || len(d.Resolver) == 0 {
		return nil, errors.New("installing split-DNS resolver config requires at least one domain and one resolver IP")
	}

	existing, err := LoadState(statePath)
	if err != nil {
		return nil, err
	}

	var state *State
	switch o.GoOS {
	case "darwin":
		state, err = o.installDarwin(cfg, d, existing)
	case "linux":
		state, err = o.installLinux(cfg, d, existing)
	default:
		return nil, fmt.Errorf("split-DNS resolver automation is not supported on %s; apply the printed commands manually", o.GoOS)
	}
	if err != nil {
		return nil, err
	}

	state.Platform = o.GoOS
	state.Connection = cfg.Name
	state.AccountID = cfg.AccountID
	state.Domains = d.Domains
	state.Resolver = d.Resolver
	state.ToNS = d.ToNS
	state.InstalledAt = nowRFC3339()

	if err := saveState(statePath, state); err != nil {
		warnings, removeErr := o.Remove(state)
		for _, warning := range warnings {
			fmt.Fprintln(os.Stderr, "WARNING: "+warning)
		}
		if removeErr != nil {
			return nil, errors.Join(fmt.Errorf("recording split-DNS state: %w", err),
				fmt.Errorf("rolling back resolver config: %w", removeErr))
		}
		return nil, fmt.Errorf("recording split-DNS state: %w", err)
	}
	return state, nil
}

// Remove tears down exactly what an earlier Install recorded.
// Warnings (foreign-dependency situations like files edited since install)
// are returned for the caller to print; removal is not failed because of them.
func Remove(state *State) (warnings []string, err error) {
	return DefaultOptions().Remove(state)
}

// Remove is the options-parametrized variant used by tests.
func (o *Options) Remove(state *State) ([]string, error) {
	if state == nil {
		return nil, nil
	}
	switch o.GoOS {
	case "darwin":
		return o.removeDarwin(state)
	case "linux":
		return o.removeLinux(state)
	default:
		return nil, fmt.Errorf("split-DNS resolver automation is not supported on %s", o.GoOS)
	}
}

// SetupInstructions renders copy-paste shell commands that put the OS
// resolver config in place for cfg's split-DNS settings (for the
// non-managed print-only workflow).
func SetupInstructions(cfg *config.Config) string {
	if cfg == nil || cfg.DNS == nil {
		return ""
	}
	o := DefaultOptions()
	switch o.GoOS {
	case "darwin":
		return o.darwinSetupInstructions(cfg.Name, cfg.DNS)
	case "linux":
		return o.linuxSetupInstructions(cfg.Name, cfg.DNS)
	default:
		return ""
	}
}

// TeardownInstructions renders the copy-paste removal commands matching
// SetupInstructions.
func TeardownInstructions(cfg *config.Config) string {
	if cfg == nil || cfg.DNS == nil {
		return ""
	}
	o := DefaultOptions()
	switch o.GoOS {
	case "darwin":
		return o.darwinTeardownInstructions(cfg.Name, cfg.DNS)
	case "linux":
		return o.linuxTeardownInstructions(cfg.Name)
	default:
		return ""
	}
}

// run wraps Run with a descriptive error including command output.
func (o *Options) run(name string, args ...string) ([]byte, error) {
	out, err := o.Run(name, args...)
	if err != nil {
		return out, fmt.Errorf("%s %s: %w: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(out)))
	}
	return out, nil
}

// needsSudo reports whether elevated privileges are required for system
// configuration commands.
func (o *Options) needsSudo() bool {
	return o.EUID != 0
}

// sudoPrefix returns the argv prefix for privileged commands.
func (o *Options) sudoPrefix() []string {
	if o.needsSudo() {
		return []string{"sudo"}
	}
	return nil
}

// runSudo runs a system configuration command, inserting "sudo" when the
// process is not already running as root. Before the first sudo use it
// fails fast when no interactive terminal is attached (a prompt with no TTY
// would otherwise wedge or fail confusingly).
func (o *Options) runSudo(name string, args ...string) ([]byte, error) {
	if !o.needsSudo() {
		return o.run(name, args...)
	}
	if err := o.ensureSudoUsable(); err != nil {
		return nil, err
	}
	return o.run("sudo", append([]string{name}, args...)...)
}

// ErrSudoUnavailable is returned when system resolver changes need root
// privileges but sudo cannot ask for a password: no cached timestamp and
// no interactive terminal (the browser TUI owns the terminal, so it sets
// TerminalIn=false to keep sudo from wedging on a hidden prompt).
var ErrSudoUnavailable = errors.New("split-DNS resolver management needs root access")

func (o *Options) ensureSudoUsable() error {
	if _, err := o.Run("sudo", "-n", "true"); err == nil {
		return nil
	}
	if o.TerminalIn {
		return nil // sudo can prompt for a password; let it.
	}
	return fmt.Errorf("%w: sudo has no cached timestamp and there is no terminal to prompt in — run `sudo -v` in the terminal running bastionctl, then start the connection again", ErrSudoUnavailable)
}

// sudoHint prefixes printed instructions with "sudo " when applicable.
func (o *Options) sudoHint() string {
	if o.needsSudo() {
		return "sudo "
	}
	return ""
}

// firstLine returns the trimmed first line of raw file content.
func firstLine(data []byte) string {
	line, _, _ := strings.Cut(string(data), "\n")
	return strings.TrimSpace(line)
}

// headerConnection extracts the connection name from a bastionctl-generated
// header line; "" when the line is not one of ours.
func headerConnection(line string) string {
	rest, ok := strings.CutPrefix(line, generatedHeaderPrefix)
	if !ok {
		return ""
	}
	fields := strings.Fields(rest)
	if len(fields) == 0 {
		return ""
	}
	return fields[0]
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

func nowRFC3339() string {
	return time.Now().UTC().Format(time.RFC3339)
}
