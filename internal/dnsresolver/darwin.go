package dnsresolver

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"bastionctl/internal/config"
)

// darwinResolverContent renders one /etc/resolver/<domain> file. macOS
// consults these files for per-domain resolution, so every split domain
// gets its own file pointing at the tunnel resolver.
func darwinResolverContent(connection string, resolvers []string) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "%s%s\n", generatedHeaderPrefix, connection)
	for _, ip := range resolvers {
		fmt.Fprintf(&b, "nameserver %s\n", ip)
	}
	b.WriteString("port 53\n")
	return []byte(b.String())
}

// installDarwin writes one /etc/resolver file per split domain.
//
// Order of operations matters: every conflict is detected (and the install
// refused) before anything is written, then stale entries from the previous
// install of the same connection are removed, then the new files are placed.
// A failure partway rolls back the files already placed.
func (o *Options) installDarwin(cfg *config.Config, d *config.DNSConfig, existing *State) (*State, error) {
	type target struct {
		path    string
		content []byte
	}
	var targets []target
	for _, domain := range d.Domains {
		dest := filepath.Join(o.EtcResolverDir, domain)
		content := darwinResolverContent(cfg.Name, d.Resolver)
		data, readErr := os.ReadFile(dest)
		switch {
		case os.IsNotExist(readErr):
			// Fresh install.
		case readErr != nil:
			return nil, readErr
		default:
			line := firstLine(data)
			if connection := headerConnection(line); strings.HasPrefix(line, generatedHeaderPrefix) {
				if connection == "" {
					return nil, fmt.Errorf("%s is a bastionctl-generated resolver file with an unreadable header; refusing to overwrite", dest)
				}
				if connection != cfg.Name {
					return nil, fmt.Errorf("%s is managed by connection %q; tear that connection down first (bastionctl --dns-teardown <name>)", dest, connection)
				}
			} else {
				return nil, fmt.Errorf("%s already exists and was not generated by bastionctl; refusing to overwrite", dest)
			}
		}
		targets = append(targets, target{path: dest, content: content})
	}

	// Reconcile: drop this connection's previously installed entries whose
	// domains are no longer split.
	if existing != nil && existing.Platform == "darwin" {
		wanted := make(map[string]struct{}, len(targets))
		for _, t := range targets {
			wanted[t.path] = struct{}{}
		}
		for _, record := range existing.Files {
			if _, keep := wanted[record.Path]; keep {
				continue
			}
			if _, warn, err := o.removeManagedFile(record, existing.Connection); err != nil {
				return nil, err
			} else if warn != "" {
				fmt.Fprintln(os.Stderr, "WARNING: "+warn)
			}
		}
	}

	if _, err := os.Stat(o.EtcResolverDir); os.IsNotExist(err) {
		if _, err := o.runSudo("install", "-d", "-m", "755", o.EtcResolverDir); err != nil {
			return nil, err
		}
	}

	var placed []string
	var records []FileRecord
	rollbackInstalled := func(cause error) error {
		for _, path := range placed {
			_, _, _ = o.removeManagedFile(FileRecord{Path: path}, cfg.Name)
		}
		return cause
	}
	for _, t := range targets {
		tmp, err := os.CreateTemp("", "bastionctl-resolver-*")
		if err != nil {
			return nil, rollbackInstalled(err)
		}
		tmpName := tmp.Name()
		if err := func() error {
			if _, err := tmp.Write(t.content); err != nil {
				return err
			}
			if err := tmp.Chmod(0o644); err != nil {
				return err
			}
			return tmp.Close()
		}(); err != nil {
			_ = os.Remove(tmpName)
			return nil, rollbackInstalled(err)
		}
		if _, err := o.runSudo("install", "-m", "644", "-o", "root", "-g", "wheel", tmpName, t.path); err != nil {
			_ = os.Remove(tmpName)
			return nil, rollbackInstalled(err)
		}
		_ = os.Remove(tmpName)
		placed = append(placed, t.path)
		records = append(records, FileRecord{Path: t.path, SHA256: sha256Hex(t.content)})
	}
	return &State{Files: records}, nil
}

// removeManagedFile removes one previously managed resolver file unless it
// is unsafe to do so. Returns a warning string when the file was left in
// place (or changed since install) so callers can surface it.
func (o *Options) removeManagedFile(record FileRecord, connection string) (removed bool, warning string, err error) {
	data, err := os.ReadFile(record.Path)
	if os.IsNotExist(err) {
		return false, "", nil
	}
	if err != nil {
		return false, "", err
	}
	line := firstLine(data)
	if !strings.HasPrefix(line, generatedHeaderPrefix) {
		return false, fmt.Sprintf("%s was not generated by bastionctl; leaving it in place", record.Path), nil
	}
	owner := headerConnection(line)
	if owner == "" {
		return false, fmt.Sprintf("%s has an unreadable bastionctl header; leaving it in place", record.Path), nil
	}
	if owner != connection {
		return false, fmt.Sprintf("%s is managed by connection %q; leaving it in place", record.Path, owner), nil
	}
	warning = ""
	if sha256Hex(data) != record.SHA256 {
		warning = fmt.Sprintf("%s changed since bastionctl installed it; removing anyway", record.Path)
	}
	if _, err := o.runSudo("rm", "-f", record.Path); err != nil {
		return false, "", err
	}
	return true, warning, nil
}

func (o *Options) removeDarwin(state *State) ([]string, error) {
	var warnings []string
	for _, record := range state.Files {
		_, warn, err := o.removeManagedFile(record, state.Connection)
		if warn != "" {
			warnings = append(warnings, warn)
		}
		if err != nil {
			return warnings, err
		}
	}
	return warnings, nil
}

// darwinSetupInstructions renders copy-paste commands matching the exact
// install path for the operator who runs bastionctl without --manage-dns.
func (o *Options) darwinSetupInstructions(name string, d *config.DNSConfig) string {
	sudo := o.sudoHint()
	var b strings.Builder
	fmt.Fprintf(&b, "%sinstall -d -m 755 %s\n", sudo, o.EtcResolverDir)
	for _, domain := range d.Domains {
		fmt.Fprintf(&b, "%stee %s >/dev/null <<'EOF'\n", sudo, filepath.Join(o.EtcResolverDir, domain))
		b.Write(darwinResolverContent(name, d.Resolver))
		b.WriteString("EOF\n")
	}
	return b.String()
}

func (o *Options) darwinTeardownInstructions(name string, d *config.DNSConfig) string {
	sudo := o.sudoHint()
	var b strings.Builder
	for _, domain := range d.Domains {
		fmt.Fprintf(&b, "%srm -f %s\n", sudo, filepath.Join(o.EtcResolverDir, domain))
	}
	return b.String()
}
